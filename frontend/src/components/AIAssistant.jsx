
import { useState } from "react";
import {
    AlertCircle,
    Bot,
    ChevronDown,
    ChevronUp,
    Database,
    LoaderCircle,
    Send,
    Sparkles,
    Trash2,
    UserRound,
} from "lucide-react";

import { askAI } from "../api/ai";
import { useAuth } from "../context/AuthContext";

const COMMON_QUESTIONS = [
    "How many technicians are registered?",
    "How many services are available?",
    "What are the services available?",
    "Which technician has the highest rating?",
    "How can I use the service portal?",
];

const CUSTOMER_QUESTIONS = [
    "How many service requests do I have?",
    "Show my service requests.",
    "Show my completed requests.",
    "Show my pending requests.",
    "Show my service request history.",
    "How many completed requests do I have?",
    "How do I create a service request?",
    "How do I cancel a service request?",
    "How do I submit feedback?",
];

const TECHNICIAN_QUESTIONS = [
    "How many service requests do I have?",
    "Show my service requests.",
    "Show my completed requests.",
    "Show my pending requests.",
    "Show my service request history.",
    "How many completed requests do I have?",
    "How do I update my availability?",
    "How do I update a service request status?",
    "How do I update my location?",
];

function formatCell(value) {
    if (value === null || value === undefined) {
        return "—";
    }

    if (typeof value === "object") {
        return JSON.stringify(value);
    }

    return String(value);
}

function formatColumnName(column) {
    return column
        .replaceAll("_", " ")
        .replace(/\b\w/g, (character) => character.toUpperCase());
}

function ResultsTable({ results }) {
    if (!results || results.length === 0) {
        return null;
    }

    const columns = [
        ...new Set(results.flatMap((row) => Object.keys(row))),
    ];

    return (
        <div className="mt-4 max-w-full overflow-x-auto rounded-xl border border-slate-200">
            <table className="min-w-full divide-y divide-slate-200 text-left text-sm">
                <thead className="bg-slate-100">
                    <tr>
                        {columns.map((column) => (
                            <th
                                key={column}
                                className="whitespace-nowrap px-4 py-3 font-semibold text-slate-700"
                            >
                                {formatColumnName(column)}
                            </th>
                        ))}
                    </tr>
                </thead>

                <tbody className="divide-y divide-slate-100 bg-white">
                    {results.map((row, rowIndex) => (
                        <tr key={rowIndex}>
                            {columns.map((column) => (
                                <td
                                    key={column}
                                    className="whitespace-nowrap px-4 py-3 text-slate-600"
                                >
                                    {formatCell(row[column])}
                                </td>
                            ))}
                        </tr>
                    ))}
                </tbody>
            </table>
        </div>
    );
}

function getAnswerSummary(response) {
    // Prefer the human-readable answer generated by the backend.
    if (
        typeof response?.answer === "string" &&
        response.answer.trim()
    ) {
        return response.answer;
    }

    // Fallback for responses that do not contain an answer.
    const results = response?.results ?? [];

    if (results.length === 0) {
        return "No matching records were found.";
    }

    const firstRow = results[0];

    if (firstRow.technician_count !== undefined) {
        return `${firstRow.technician_count} technician(s) are registered in the system.`;
    }

    if (firstRow.service_count !== undefined) {
        return `${firstRow.service_count} service(s) are available in the system.`;
    }

    if (firstRow.request_count !== undefined) {
        return `You have ${firstRow.request_count} matching service request(s).`;
    }

    if (
        firstRow.technician_name !== undefined &&
        firstRow.rating !== undefined
    ) {
        if (results.length === 1) {
            return `${firstRow.technician_name} has the highest rating: ${firstRow.rating}/5.`;
        }

        return `${results.length} technicians share the highest rating of ${firstRow.rating}/5.`;
    }

    return `${results.length} record(s) returned.`;
}

function ChatMessage({ message }) {
    const [showSQL, setShowSQL] = useState(false);

    const isUser = message.role === "user";
    const response = message.response;

    return (
        <div
            className={`flex gap-3 ${
                isUser ? "flex-row-reverse" : "flex-row"
            }`}
        >
            <div
                className={`flex h-9 w-9 shrink-0 items-center justify-center rounded-full ${
                    isUser
                        ? "bg-blue-600 text-white"
                        : "bg-violet-100 text-violet-700"
                }`}
            >
                {isUser ? <UserRound size={18} /> : <Bot size={19} />}
            </div>

            <div
                className={`min-w-0 max-w-[95%] rounded-2xl p-4 sm:max-w-[90%] ${
                    isUser
                        ? "rounded-tr-sm bg-blue-600 text-white"
                        : "rounded-tl-sm border border-slate-200 bg-white text-slate-800 shadow-sm"
                }`}
            >
                {isUser ? (
                    <p className="whitespace-pre-wrap text-sm">
                        {message.content}
                    </p>
                ) : message.error ? (
                    <div>
                        <p className="text-sm font-medium">
                            Unable to answer your question.
                        </p>

                        <div className="mt-2 flex items-start gap-2 text-sm text-red-600">
                            <AlertCircle
                                size={17}
                                className="mt-0.5 shrink-0"
                            />
                            <p className="whitespace-pre-wrap">
                                {message.content}
                            </p>
                        </div>
                    </div>
                ) : (
                    <div>
                        <div className="flex items-center gap-2">
                            <Sparkles
                                size={17}
                                className="text-violet-600"
                            />
                            <p className="text-sm font-semibold">
                                AI Assistant
                            </p>
                        </div>

                        <p className="mt-3 whitespace-pre-wrap text-sm leading-6 text-slate-600">
                            {getAnswerSummary(response)}
                        </p>

                        <ResultsTable
                            results={response?.results ?? []}
                        />

                        {response?.result_count !== undefined && (
                            <p className="mt-3 text-xs text-slate-400">
                                {response.result_count} matching record(s)
                            </p>
                        )}

                        {response?.sql && (
                            <div className="mt-4 border-t border-slate-200 pt-3">
                                <button
                                    type="button"
                                    onClick={() =>
                                        setShowSQL((previous) => !previous)
                                    }
                                    className="flex items-center gap-2 text-xs font-semibold text-slate-500 transition hover:text-slate-800"
                                >
                                    <Database size={15} />
                                    SQL query

                                    {showSQL ? (
                                        <ChevronUp size={15} />
                                    ) : (
                                        <ChevronDown size={15} />
                                    )}
                                </button>

                                {showSQL && (
                                    <pre className="mt-3 max-w-full overflow-x-auto whitespace-pre-wrap wrap-break-word rounded-lg bg-slate-950 p-3 text-xs text-green-300">
                                        {response.sql}
                                    </pre>
                                )}
                            </div>
                        )}
                    </div>
                )}
            </div>
        </div>
    );
}

function AIAssistant() {
    const { user } = useAuth();

    const [question, setQuestion] = useState("");
    const [messages, setMessages] = useState([]);
    const [loading, setLoading] = useState(false);

    const role = String(user?.role ?? "").toLowerCase();

    const roleQuestions =
        role === "customer"
            ? CUSTOMER_QUESTIONS
            : role === "technician"
              ? TECHNICIAN_QUESTIONS
              : [];

    const suggestedQuestions = [
        ...COMMON_QUESTIONS,
        ...roleQuestions,
    ];

    const handleAsk = async (submittedQuestion) => {
        const trimmedQuestion = submittedQuestion.trim();

        if (!trimmedQuestion || loading) {
            return;
        }

        setQuestion("");
        setLoading(true);

        setMessages((previous) => [
            ...previous,
            {
                id: `${Date.now()}-user`,
                role: "user",
                content: trimmedQuestion,
            },
        ]);

        try {
            const response = await askAI(trimmedQuestion);

            setMessages((previous) => [
                ...previous,
                {
                    id: `${Date.now()}-assistant`,
                    role: "assistant",
                    response,
                },
            ]);
        } catch (err) {
            const errorMessage =
                err.response?.data?.detail ||
                "Unable to get a response. Please try again.";

            setMessages((previous) => [
                ...previous,
                {
                    id: `${Date.now()}-assistant`,
                    role: "assistant",
                    content: errorMessage,
                    error: true,
                },
            ]);
        } finally {
            setLoading(false);
        }
    };

    const handleClear = () => {
        if (loading) {
            return;
        }

        setMessages([]);
        setQuestion("");
    };

    return (
        <div className="mx-auto max-w-6xl space-y-6">
            <div className="flex flex-col justify-between gap-4 sm:flex-row sm:items-center">
                <div>
                    <div className="flex items-center gap-2">
                        <div className="flex h-11 w-11 items-center justify-center rounded-2xl bg-violet-100 text-violet-700">
                            <Bot size={24} />
                        </div>

                        <div>
                            <h1 className="text-2xl font-bold text-slate-900">
                                AI Assistant
                            </h1>

                            <p className="text-sm text-slate-500">
                                Smart Database Assistant
                            </p>
                        </div>
                    </div>

                    <p className="mt-3 text-sm text-slate-600">
                        Explore services, technicians, ratings, and your
                        service requests.
                    </p>
                </div>

                {messages.length > 0 && (
                    <button
                        type="button"
                        onClick={handleClear}
                        disabled={loading}
                        className="inline-flex items-center justify-center gap-2 self-start rounded-xl border border-slate-200 bg-white px-4 py-2.5 text-sm font-medium text-slate-600 transition hover:bg-slate-50 disabled:cursor-not-allowed disabled:opacity-50 sm:self-auto"
                    >
                        <Trash2 size={16} />
                        Clear chat
                    </button>
                )}
            </div>

            <div className="overflow-hidden rounded-2xl border border-slate-200 bg-slate-50 shadow-sm">
                <div className="flex items-center gap-3 border-b border-slate-200 bg-white px-5 py-4">
                    <div className="flex h-10 w-10 items-center justify-center rounded-xl bg-violet-100 text-violet-700">
                        <Sparkles size={20} />
                    </div>

                    <div>
                        <p className="font-semibold text-slate-900">
                            Smart Assistant
                        </p>

                        <p className="text-xs text-slate-500">
                            Ask a question in natural language
                        </p>
                    </div>

                    <span className="ml-auto rounded-full bg-green-50 px-3 py-1 text-xs font-medium text-green-700">
                        AI Powered
                    </span>
                </div>

                <div className="min-h-75 space-y-5 p-4 sm:p-6">
                    {messages.length === 0 ? (
                        <div className="flex min-h-70 flex-col items-center justify-center text-center">
                            <div className="mb-4 flex h-16 w-16 items-center justify-center rounded-2xl bg-violet-100 text-violet-700">
                                <Bot size={34} />
                            </div>

                            <h2 className="text-lg font-semibold text-slate-900">
                                How can I help you?
                            </h2>

                            <p className="mt-2 max-w-md text-sm text-slate-500">
                                Choose a suggested question or type your own.
                                Suggestions are tailored to your portal.
                            </p>

                            <div className="mt-6 flex max-w-3xl flex-wrap justify-center gap-2">
                                {suggestedQuestions.map((suggestion) => (
                                    <button
                                        key={suggestion}
                                        type="button"
                                        onClick={() => handleAsk(suggestion)}
                                        disabled={loading}
                                        className="rounded-xl border border-slate-200 bg-white px-3 py-2 text-left text-xs text-slate-600 transition hover:border-violet-300 hover:bg-violet-50 hover:text-violet-700 disabled:cursor-not-allowed disabled:opacity-50 sm:text-sm"
                                    >
                                        {suggestion}
                                    </button>
                                ))}
                            </div>
                        </div>
                    ) : (
                        messages.map((message) => (
                            <ChatMessage
                                key={message.id}
                                message={message}
                            />
                        ))
                    )}

                    {loading && (
                        <div className="flex items-center gap-3">
                            <div className="flex h-9 w-9 items-center justify-center rounded-full bg-violet-100 text-violet-700">
                                <Bot size={19} />
                            </div>

                            <div className="flex items-center gap-2 rounded-xl border border-slate-200 bg-white px-4 py-3 text-sm text-slate-500">
                                <LoaderCircle
                                    size={17}
                                    className="animate-spin"
                                />
                                Analyzing your question...
                            </div>
                        </div>
                    )}
                </div>

                <form
                    onSubmit={(event) => {
                        event.preventDefault();
                        handleAsk(question);
                    }}
                    className="border-t border-slate-200 bg-white p-4 sm:p-5"
                >
                    <div className="flex items-end gap-3 rounded-xl border border-slate-200 bg-slate-50 p-2 focus-within:border-violet-400 focus-within:ring-2 focus-within:ring-violet-100">
                        <textarea
                            value={question}
                            onChange={(event) =>
                                setQuestion(event.target.value)
                            }
                            onKeyDown={(event) => {
                                if (
                                    event.key === "Enter" &&
                                    !event.shiftKey
                                ) {
                                    event.preventDefault();
                                    handleAsk(question);
                                }
                            }}
                            placeholder="Ask your question..."
                            rows={2}
                            maxLength={1000}
                            disabled={loading}
                            className="max-h-36 min-h-12 flex-1 resize-y bg-transparent px-3 py-3 text-sm text-slate-800 outline-none placeholder:text-slate-400 disabled:opacity-50"
                        />

                        <button
                            type="submit"
                            disabled={!question.trim() || loading}
                            className="mb-1 flex h-10 w-10 shrink-0 items-center justify-center rounded-xl bg-violet-600 text-white transition hover:bg-violet-700 disabled:cursor-not-allowed disabled:opacity-40"
                            aria-label="Send question"
                        >
                            {loading ? (
                                <LoaderCircle
                                    size={18}
                                    className="animate-spin"
                                />
                            ) : (
                                <Send size={18} />
                            )}
                        </button>
                    </div>

                    <p className="mt-2 text-xs text-slate-400">
                        Press Enter to send. Press Shift + Enter for a new line.
                    </p>
                </form>
            </div>
        </div>
    );
}

export default AIAssistant;
